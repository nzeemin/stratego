# map2inc.ps1 - turn the z88dk link map into a sjasmplus include for strateg1.asm
#
#   core.map  ->  core.inc
#
# Emits: CORE_ORG / CORE_END / CORE_SIZE / CORE_FREE,
#        entry-point EQUs (leading '_' stripped),
#        g_state address, and the GS_* GameState field offsets.

param(
    [Parameter(Mandatory=$true)][string]$Map,
    [Parameter(Mandatory=$true)][string]$Out
)

$ErrorActionPreference = 'Stop'

# C symbols to export as call targets / data addresses.
$wanted = @(
    'rng_seed','rng_next','rng_range',
    'ai_reset','ai_choose_move','ai_gen_move','ai_scout_move',
    'ai_check_enemy','ai_find_nearest',
    'game_new','game_setup_computer','game_setup_player_random',
    'game_rebuild_grid','game_legal','game_apply',
    'game_check_loss','game_count_alive',
    'g_state','g_ai'
)

$lines = Get-Content -LiteralPath $Map
$sym = @{}
foreach ($ln in $lines) {
    # e.g.  _ai_choose_move                 = $79F7 ; addr, public, ...
    if ($ln -match '^\s*(_?[A-Za-z_][A-Za-z0-9_]*)\s*=\s*\$([0-9A-Fa-f]+)') {
        $name = $matches[1]
        $val  = [Convert]::ToInt32($matches[2],16)
        if (-not $sym.ContainsKey($name)) { $sym[$name] = $val }
    }
}

function Need($n) {
    if (-not $sym.ContainsKey($n)) { throw "symbol '$n' not found in $Map" }
    return $sym[$n]
}

$org  = Need '__head'
$end  = Need '__tail'
$size = $end - $org
$ceil = 0xA000           # the screen starts here; core must stay below
$free = $ceil - $end

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine(';  Generated by tools\map2inc.ps1 - do not edit.')
[void]$sb.AppendLine(';  Stratego game core (z88dk / sccz80) entry points and layout.')
[void]$sb.AppendLine(';  sccz80 call convention: args pushed left->right, caller cleans,')
[void]$sb.AppendLine(';  8-bit result in L, 16-bit in HL.')
[void]$sb.AppendLine('')
[void]$sb.AppendLine(('CORE_ORG        EQU 0{0:X4}h' -f $org))
[void]$sb.AppendLine(('CORE_END        EQU 0{0:X4}h' -f $end))
[void]$sb.AppendLine(('CORE_SIZE       EQU 0{0:X4}h' -f $size))
[void]$sb.AppendLine(('CORE_FREE       EQU 0{0:X4}h   ; bytes from CORE_END up to the screen at 0A000h' -f $free))
[void]$sb.AppendLine('')

if ($sym.ContainsKey('core_vectors')) {
    [void]$sb.AppendLine(('CORE_VECTORS    EQU 0{0:X4}h   ; jp table base' -f $sym['core_vectors']))
    [void]$sb.AppendLine('')
}

[void]$sb.AppendLine('; --- entry points --------------------------------------------------')
foreach ($w in $wanted) {
    $key = '_' + $w
    if ($sym.ContainsKey($key))      { $v = $sym[$key] }
    elseif ($sym.ContainsKey($w))    { $v = $sym[$w] }
    else { Write-Warning "missing: $w"; continue }
    [void]$sb.AppendLine(('{0,-24} EQU 0{1:X4}h' -f $w, $v))
}

[void]$sb.AppendLine('')
[void]$sb.AppendLine('; --- GameState field offsets (stratego.h, sccz80 packing, align 1) -')
[void]$sb.AppendLine('GS_comp                  EQU 0      ; Piece[40], 3 bytes each')
[void]$sb.AppendLine('GS_play                  EQU 120')
[void]$sb.AppendLine('GS_known                 EQU 240    ; u8[40]')
[void]$sb.AppendLine('GS_emoved                EQU 280    ; u8[40]')
[void]$sb.AppendLine('GS_moved                 EQU 320    ; u8[40]')
[void]$sb.AppendLine('GS_grid                  EQU 360    ; u8[100], CELL(c,r) = grid[r*10+c]')
[void]$sb.AppendLine('GS_pleft                 EQU 460')
[void]$sb.AppendLine('GS_guard_id              EQU 461')
[void]$sb.AppendLine('GS_gx                    EQU 462')
[void]$sb.AppendLine('GS_gy                    EQU 463')
[void]$sb.AppendLine('GS_mdflag                EQU 464')
[void]$sb.AppendLine('GS_SIZE                  EQU 465')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('PIECE_value              EQU 0')
[void]$sb.AppendLine('PIECE_col                EQU 1')
[void]$sb.AppendLine('PIECE_row                EQU 2')
[void]$sb.AppendLine('PIECE_SIZE               EQU 3')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('MV_score                 EQU 0      ; Move: s16 score')
[void]$sb.AppendLine('MV_col                   EQU 2')
[void]$sb.AppendLine('MV_row                   EQU 3')
[void]$sb.AppendLine('MV_attack                EQU 4')
[void]$sb.AppendLine('MV_urgent                EQU 5')
[void]$sb.AppendLine('MV_SIZE                  EQU 6')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('CB_fought                EQU 0      ; Combat')
[void]$sb.AppendLine('CB_att_value             EQU 1')
[void]$sb.AppendLine('CB_def_value             EQU 2')
[void]$sb.AppendLine('CB_att_id                EQU 3')
[void]$sb.AppendLine('CB_def_id                EQU 4')
[void]$sb.AppendLine('CB_result                EQU 5      ; BO_*: 0 both die, 1 attacker wins, 2 defender wins')
[void]$sb.AppendLine('CB_flag_taken            EQU 6')
[void]$sb.AppendLine('CB_SIZE                  EQU 7')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('SIDE_COMP                EQU 0')
[void]$sb.AppendLine('SIDE_PLAY                EQU 1')

Set-Content -LiteralPath $Out -Value $sb.ToString() -Encoding ASCII
Write-Host ("map2inc: {0} symbols, ORG {1:X4}h END {2:X4}h SIZE {3} FREE {4}" -f $sym.Count, $org, $end, $size, $free)
