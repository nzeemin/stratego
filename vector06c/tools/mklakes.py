#!/usr/bin/env python3
"""Extract the two lakes from the game field picture (field.png, 160x200)
as two 32x40 1-bit bitmaps and write them as assembler data (strategt.asm).

A lake pixel is a pixel of the lake color (71B4A7).  The lakes are the cells
c4 c5 d4 d5 (columns 2-3) and g4 g5 h4 h5 (columns 6-7) of rows 4-5; a cell is
16x20 pixels, so the areas are x 32..63 and 96..127, y 80..119.

Output, per lake (160 bytes), in screen order for the Vector-06C (column
oriented screen, see CLAUDE.md): four xbyte columns left to right, each 40
bytes from the top row to the bottom row.  Bit 7 is the leftmost pixel.

Usage (from vector06c/):
    python tools\\mklakes.py [field.png [strategt.asm]]
"""
import argparse
import sys

from PIL import Image

LAKE = (0x71, 0xB4, 0xA7)
CELL_W, CELL_H = 16, 20
LAKES = [("Lake1Gfx", 2, 4), ("Lake2Gfx", 6, 4)]   # name, column, row of the top-left cell
W, H = 2 * CELL_W, 2 * CELL_H                       # 32 x 40


def hexb(b):
    s = "%02X" % b
    return ("0" + s if s[0].isalpha() else s) + "h"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("png", nargs="?", default="field.png")
    ap.add_argument("asm", nargs="?", default="strategt.asm")
    a = ap.parse_args()

    im = Image.open(a.png).convert("RGB")
    if im.size != (160, 200):
        sys.exit("%s: expected 160x200, got %dx%d" % ((a.png,) + im.size))

    with open(a.asm, "w", newline="\r\n") as f:
        f.write("; strategt.asm - the lakes of the game field, generated by tools\\mklakes.py\n")
        f.write("; from %s.  Do not edit.  Two 32x40 1-bit bitmaps, 160 bytes each:\n" % a.png)
        f.write("; four xbyte columns left to right, each 40 bytes from the top row down.\n")
        for name, col, row in LAKES:
            x0, y0 = col * CELL_W, row * CELL_H
            cols = []
            for xb in range(W // 8):
                data = []
                for y in range(H):
                    b = 0
                    for bit in range(8):
                        if im.getpixel((x0 + xb * 8 + bit, y0 + y)) == LAKE:
                            b |= 0x80 >> bit
                    data.append(b)
                cols.append(data)
            f.write("%s:\t\t\t; cells %s%d..%s%d\n" % (
                name, "ABCDEFGHIJ"[col], row, "ABCDEFGHIJ"[col + 1], row + 1))
            for data in cols:
                f.write("\tDB " + ",".join(hexb(b) for b in data[:20]) + "\n")
                f.write("\tDB " + ",".join(hexb(b) for b in data[20:]) + "\n")
            print(name)
            for y in range(H):
                print("  " + "".join(format(cols[xb][y], "08b") for xb in range(W // 8))
                      .replace("0", ".").replace("1", "#"))
        f.write("LakesGfxEnd:\n")
    print("%s: %d bytes" % (a.asm, 2 * (W // 8) * H))


if __name__ == "__main__":
    main()
