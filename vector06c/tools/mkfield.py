#!/usr/bin/env python3
"""Convert the game field picture (field.png, 160x200) to the background image.

The field is shown with the screen's A000h plane set (palette indexes 4..7), so
each background pixel has a 2-bit color k: bit 1 is stored in the C000h plane,
bit 0 in the E000h plane.  Colors, in the order k = 0..3 (change with --colors):
black, brown, yellow, green.  Pixels of the lake color are foreground (drawn
separately); under them the nearest background pixel of the same row is used.

Outputs:
  strategb.bin   8000 bytes: the C000h plane (4000 bytes) then the E000h plane
                 (4000 bytes).  Each plane is column oriented like the screen:
                 20 xbyte columns left to right, each 200 rows from the top down,
                 so byte (xbyte x, row j) is at x*200 + j.  Bit 7 = leftmost pixel.
  strategb.inc   FieldPalette: the palette bytes (BBGGGRRR) of the four colors,
                 for the palette entries 4..7.

Usage (from vector06c/):
    python tools\\mkfield.py [field.png [strategb.bin [strategb.inc]]] [--preview out.png]
"""
import argparse
import sys

from PIL import Image

W, H = 160, 200
LAKE = (0x71, 0xB4, 0xA7)
DEFAULT_COLORS = "000000,714B00,8E7100,4B4B00"   # black, brown, yellow, green


def rgb(s):
    s = s.strip().lstrip("#")
    return (int(s[0:2], 16), int(s[2:4], 16), int(s[4:6], 16))


def palette_byte(c):
    """Vector-06C palette byte: bits 0-2 red, 3-5 green, 6-7 blue."""
    r = round(c[0] * 7 / 255)
    g = round(c[1] * 7 / 255)
    b = round(c[2] * 3 / 255)
    return (b << 6) | (g << 3) | r


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("png", nargs="?", default="field.png")
    ap.add_argument("bin", nargs="?", default="strategb.bin")
    ap.add_argument("inc", nargs="?", default="strategb.inc")
    ap.add_argument("--colors", default=DEFAULT_COLORS,
                    help="four RRGGBB colors for k = 0..3, comma separated")
    ap.add_argument("--preview", help="write the converted picture as a PNG")
    a = ap.parse_args()

    colors = [rgb(s) for s in a.colors.split(",")]
    if len(colors) != 4:
        sys.exit("--colors needs exactly four colors")
    im = Image.open(a.png).convert("RGB")
    if im.size != (W, H):
        sys.exit("%s: expected %dx%d, got %dx%d" % ((a.png, W, H) + im.size))

    # color index per pixel, None for the lake
    k = [[None] * W for _ in range(H)]
    for y in range(H):
        for x in range(W):
            p = im.getpixel((x, y))
            if p == LAKE:
                continue
            if p not in colors:
                sys.exit("%s: pixel (%d,%d) has color %02X%02X%02X which is not one "
                         "of the four background colors" % ((a.png, x, y) + p))
            k[y][x] = colors.index(p)
    lake = 0
    for y in range(H):
        for x in range(W):
            if k[y][x] is None:
                lake += 1
                d = 1
                while True:
                    for xx in (x - d, x + d):
                        if 0 <= xx < W and k[y][xx] is not None:
                            k[y][x] = k[y][xx]
                            break
                    if k[y][x] is not None:
                        break
                    d += 1
    # lake pixels were filled from their neighbours, which may themselves be lake
    # pixels filled earlier in the same row: that is fine, the value is only a
    # placeholder under the foreground

    planes = [bytearray(), bytearray()]            # C000h (bit 1), E000h (bit 0)
    for xb in range(W // 8):
        for y in range(H):
            c = e = 0
            for bit in range(8):
                v = k[y][xb * 8 + bit]
                c |= ((v >> 1) & 1) << (7 - bit)
                e |= (v & 1) << (7 - bit)
            planes[0].append(c)
            planes[1].append(e)
    with open(a.bin, "wb") as f:
        f.write(planes[0])
        f.write(planes[1])

    pal = [palette_byte(c) for c in colors]
    with open(a.inc, "w", newline="\r\n") as f:
        f.write("; strategb.inc - generated by tools\\mkfield.py from %s.  Do not edit.\n" % a.png)
        f.write("; Palette bytes (BBGGGRRR) of the background colors, for the palette\n")
        f.write("; entries 4..7: black, brown, yellow, green.\n")
        f.write("FieldPalette:\n\tDB " + ",".join("%03Xh" % v if v > 0x9F else "%02Xh" % v for v in pal) + "\n")
        f.write("FIELD_PLANE_SIZE\tEQU %d\n" % len(planes[0]))

    if a.preview:
        out = Image.new("RGB", (W, H))
        for y in range(H):
            for x in range(W):
                out.putpixel((x, y), colors[k[y][x]])
        out.save(a.preview)

    counts = [sum(row.count(i) for row in k) for i in range(4)]
    print("%s: %d bytes (2 planes of %d); lake pixels replaced: %d" %
          (a.bin, 2 * len(planes[0]), len(planes[0]), lake))
    print("colors k=0..3 %s: %s" % (counts, " ".join("%02X" % v for v in pal)))


if __name__ == "__main__":
    main()
