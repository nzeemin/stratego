#!/usr/bin/env python3
"""Convert the piece strip (pieces20.png) to assembler data (strategp.asm).

The strip holds one 16x16 face per piece, left to right, in rank order:
spy, 2..9 (scout .. general), marshal, bomb, flag.  Only white pixels matter
(any other color is 0).

Output, per piece (32 bytes), in screen order for the Vector-06C
(column-oriented screen, see CLAUDE.md): the left xbyte column from the top
row to the bottom row (16 bytes), then the right xbyte column (16 bytes).
Bit 7 is the leftmost pixel of a byte.

Usage (from vector06c/):
    python tools\\mkpieces.py [pieces20.png [strategp.asm]]
"""
import argparse
import sys

from PIL import Image

NAMES = ["SPY", "2 SCOUT", "3 MINER", "4 SERGEANT", "5 LIEUTENANT",
         "6 CAPTAIN", "7 MAJOR", "8 COLONEL", "9 GENERAL", "MARSHAL",
         "BOMB", "FLAG"]
SIZE = 16


def is_white(px):
    return min(px[:3]) >= 200


def convert(path, x0, y0):
    im = Image.open(path).convert("RGB")
    need_w = x0 + SIZE * len(NAMES)
    if im.width < need_w or im.height < y0 + SIZE:
        sys.exit("%s: %dx%d is too small for %d faces at (%d,%d)"
                 % (path, im.width, im.height, len(NAMES), x0, y0))
    out = []
    for n, name in enumerate(NAMES):
        fx = x0 + n * SIZE
        cols = []
        for half in range(2):                       # left, right xbyte
            col = []
            for y in range(SIZE):                   # top to bottom
                b = 0
                for bit in range(8):
                    if is_white(im.getpixel((fx + half * 8 + bit, y0 + y))):
                        b |= 0x80 >> bit
                col.append(b)
            cols.append(col)
        out.append((name, cols))
    return out


def hexb(b):
    s = "%02X" % b
    return ("0" + s if s[0].isalpha() else s) + "h"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("png", nargs="?", default="pieces20.png")
    ap.add_argument("asm", nargs="?", default="strategp.asm")
    ap.add_argument("--x0", type=int, default=0, help="x of the first face")
    ap.add_argument("--y0", type=int, default=1, help="y of the faces' top row")
    a = ap.parse_args()

    faces = convert(a.png, a.x0, a.y0)
    with open(a.asm, "w", newline="\r\n") as f:
        f.write("; strategp.asm - piece faces, generated by tools\\mkpieces.py from %s.\n"
                % a.png)
        f.write("; Do not edit.  16x16 white-only masks, 32 bytes per piece, indexed by\n")
        f.write("; rank-1: left xbyte column top->bottom, then right xbyte column.\n")
        f.write("PieceGfx:\n")
        for name, cols in faces:
            f.write("\t; %s\n" % name)
            for col in cols:
                f.write("\tDB " + ",".join(hexb(b) for b in col) + "\n")
        f.write("PieceGfxEnd:\n")
    print("%s: %d faces, %d bytes" % (a.asm, len(faces), len(faces) * 32))

    # quick look at the result
    for name, cols in faces:
        print(name)
        for y in range(SIZE):
            print("  " + "".join(
                format(cols[h][y], "08b") for h in range(2)
            ).replace("0", ".").replace("1", "#"))


if __name__ == "__main__":
    main()
